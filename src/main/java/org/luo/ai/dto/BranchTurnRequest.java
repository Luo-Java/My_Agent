package org.luo.ai.dto;

/**
 * 「从某一条消息处开启新版本」请求体（服务「编辑重发 / 重新生成」）。
 * <p>
 * 语义是「<b>正序前 {@code keepCount} 条保留，第 {@code keepCount} 条就是分叉点</b>」——
 * 它与「截断到前 N 条」共用同一套定位口径，区别只在于截断是删、这里是原地再开一版。
 * <p>
 * 为什么用「条数」而不是 message id：分叉点由前端决定，而<b>刚发出去那一轮的消息前端手里没有 id</b>
 * ——SSE 只回内容，不回落库主键。让前端为了拿 id 再查一次库，只为传回一个「第几条」的等价信息，
 * 是白绕一圈。而「前几条」前端天然就知道（消息数组下标），且 id 单调递增保证了两种表达完全等价。
 *
 * @param keepCount 分叉点所在的正序下标 + 1；≤0 或超出会话长度时后端返回 400（缺少安全的默认值）
 */
public record BranchTurnRequest(int keepCount) {
}
